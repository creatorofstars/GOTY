let LANG = localStorage.getItem('lang') || 'zh';
function t(k) { return (I18N[LANG] && I18N[LANG][k]) || I18N.zh[k] || k; }
/** 用参数填充 {xxx} 占位符 */
function tf(k, args) { return t(k).replace(/\{(\w+)\}/g, (_, n) => args[n] != null ? args[n] : ''); }
function applyI18n() {
  document.documentElement.lang = LANG === 'en' ? 'en' : 'zh-CN';
  document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = t(el.dataset.i18nPh); });
  document.querySelectorAll('.lang-btn').forEach(b => b.classList.toggle('active', b.dataset.lang === LANG));
  window.dispatchEvent(new CustomEvent('langchange'));
}
function setLang(l) { if (!I18N[l] || l === LANG) return; LANG = l; localStorage.setItem('lang', l); applyI18n(); }
document.querySelectorAll('.lang-btn').forEach(b => { b.addEventListener('click', () => setLang(b.dataset.lang)); });
applyI18n();
